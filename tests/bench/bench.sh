#!/bin/sh
# Benchmark driver (docs/benchmarks.md). Standalone luau cannot read or write
# files, so this script prepares the inputs and stores the report:
#
#   bench.sh run [run.luau args...]     embed fixtures and plugin sources, run
#                                       tests/bench/run.luau, save the JSON report
#                                       as tests/bench/out/<UTC stamp>.json and
#                                       tests/bench/out/latest.json
#   bench.sh compare BASE [NEW]         compare two reports (NEW defaults to
#                                       tests/bench/out/latest.json)
#   bench.sh profile [run.luau args...] sample the run with luau --profile and
#                                       print the hottest functions (self and
#                                       inclusive time)
#
# BENCH_LUAU_FLAGS overrides the luau flags (default --codegen: Tern runs
# plugins natively compiled; use -O1 for the interpreter `make test` uses).
set -eu

cd "$(dirname "$0")/../.."

LUAU=.tools/bin/luau
FLAGS=${BENCH_LUAU_FLAGS---codegen}
out=tests/bench/out
mkdir -p "$out"

[ -x "$LUAU" ] || {
	echo "bench: missing $LUAU: run 'make bootstrap'" >&2
	exit 1
}

# tests/bench/out/sources.luau: every shipped module's source, plus the list
# of modules plugin/window.luau loads (taken from check-window-load.sh, which
# prints that list with byte counts when over budget; budget 0 forces it).
sources() {
	tmp="$out/sources.luau.tmp.$$"
	window=$(sh scripts/check-window-load.sh 0 2>&1 | awk '$1 ~ /^[0-9]+$/ && $2 ~ /^plugin\// { print $2 }' || true)
	[ -n "$window" ] || {
		echo "bench: could not list the window entry's modules" >&2
		exit 1
	}
	{
		printf -- '--!nocheck\n-- GENERATED by tests/bench/bench.sh; do not edit.\nreturn {\n\twindow = {\n'
		for f in $window; do
			printf '\t\t"%s",\n' "$f"
		done
		printf '\t},\n\tfiles = {\n'
		find plugin -name '*.luau' | LC_ALL=C sort | while IFS= read -r f; do
			eq="="
			while grep -qF "]$eq" "$f"; do
				eq="$eq="
			done
			printf '\t\t["%s"] = [%s[\n' "$f" "$eq"
			cat "$f"
			printf ']%s],\n' "$eq"
		done
		printf '\t},\n}\n'
	} >"$tmp"
	mv "$tmp" "$out/sources.luau"
}

prepare() {
	sh scripts/fixtures/embed.sh
	sources
}

cmd=${1:-run}
[ $# -eq 0 ] || shift
case $cmd in
run)
	prepare
	stamp=$(date -u +%Y%m%dT%H%M%SZ)
	log="$out/$stamp.txt"
	if [ "$(uname -s)" = Darwin ]; then
		cpu=$(sysctl -n machdep.cpu.brand_string)
	else
		cpu=$(awk -F': ' '/model name/ { print $2; exit }' /proc/cpuinfo 2>/dev/null || echo unknown)
	fi
	set -- "$@" \
		--meta "date=$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
		--meta "commit=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)" \
		--meta "plugin_dirty=$(if git diff --quiet HEAD -- plugin 2>/dev/null; then echo no; else echo yes; fi)" \
		--meta "luau_flags=$FLAGS" \
		--meta "os=$(uname -sm)" \
		--meta "cpu=$cpu"
	# shellcheck disable=SC2086 # FLAGS is a flag list
	"$LUAU" $FLAGS tests/bench/run.luau -a "$@" >"$log" 2>&1 || {
		cat "$log"
		exit 1
	}
	grep -v '^BENCH_JSON ' "$log"
	sed -n 's/^BENCH_JSON //p' "$log" >"$out/$stamp.json"
	cp "$out/$stamp.json" "$out/latest.json"
	echo "bench: report $out/$stamp.json (also $out/latest.json)"
	;;
compare)
	base=${1:?usage: bench.sh compare BASE [NEW]}
	new=${2:-$out/latest.json}
	"$LUAU" tests/bench/compare.luau -a "$(cat "$base")" "$(cat "$new")" "${BENCH_THRESHOLD:-10}"
	;;
profile)
	prepare
	prof="$out/profile.out"
	# The interpreter keeps every Luau frame in the samples.
	rm -f profile.out
	"$LUAU" --profile=10000 tests/bench/run.luau -a --no-phases --warmup 1 --iters 5 "$@" >/dev/null
	mv profile.out "$prof"
	# Each line: <microseconds> <leaf frame>;<caller>;...;<root>; frames are file,function,line.
	awk -v top="${BENCH_TOP:-40}" -v root="$(pwd)/" '
		BEGIN { cmd = "sort -rn | head -" top }
		{
			us = $1; $1 = ""; sub(/^ /, "")
			gsub(root, "")
			total += us
			n = split($0, frames, ";")
			self[frames[1]] += us
			delete seen
			for (i = 1; i <= n; i++) if (!(frames[i] in seen)) { seen[frames[i]] = 1; incl[frames[i]] += us }
		}
		END {
			printf "%d ms sampled\n\nself%%   incl%%  function (file,name,line)\n", total / 1000
			for (f in self) printf "%6.2f %6.2f  %s\n", 100 * self[f] / total, 100 * incl[f] / total, f | cmd
			close(cmd)
			printf "\nincl%%  function\n"
			for (f in incl) printf "%6.2f  %s\n", 100 * incl[f] / total, f | cmd
			close(cmd)
		}' "$prof"
	echo "bench: raw samples in $prof"
	;;
*)
	echo "usage: bench.sh run|compare BASE [NEW]|profile" >&2
	exit 2
	;;
esac
